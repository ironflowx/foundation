#[test]
fn two_methods_with_clashing_commands_are_refused() {
    let both = |one: &str, two: &str| {
        let options =
            |cli: &str| format!("option (ironflowx.v1.cli) = {cli:?}; {SUMMARY} {EXAMPLE}");
        generate(&format!(
            "service S {{ rpc One(M) returns (M) {{ {} }} rpc TwoTwo(M) returns (M) {{ {} }} }}\n\
             message M {{}}",
            options(one),
            options(two)
        ))
    };
    for (one, two) in [
        ("do", "do"),
        ("do", "do it"),
        ("do it", "do"),
        ("do it", "do it"),
        ("do it", "do it now"),
    ] {
        let why = "two_two: its command clashes with that of one";
        assert_eq!(both(one, two).unwrap_err(), why, "{one}, {two}");
    }
    for (one, two) in [("do", "do-it"), ("do it", "do at"), ("do it", "redo it")] {
        assert!(both(one, two).is_ok(), "{one}, {two}");
    }
}

