//! What the generator writes, and each thing it refuses.

use std::path::Path;

/// The proto's own directory, for the custom options.
const PROTO: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../ironflowx-proto/proto");

/// The descriptor set of `body`, in a file of its own that has the custom options.
fn compile(body: &str) -> Vec<u8> {
    let dir = tempfile::tempdir().unwrap();
    let file = format!(
        "syntax = \"proto3\";\npackage t;\nimport \"ironflowx/v1/options.proto\";\n\
         import \"google/protobuf/timestamp.proto\";\n\
         import \"google/protobuf/duration.proto\";\n{body}"
    );
    std::fs::write(dir.path().join("t.proto"), file).unwrap();
    protox::Compiler::new([dir.path(), Path::new(PROTO)])
        .unwrap()
        .include_imports(true)
        .open_file("t.proto")
        .unwrap()
        .encode_file_descriptor_set()
}

fn generate(body: &str) -> Result<String, String> {
    let out = tempfile::tempdir().unwrap();
    ironflowx_codegen::generate(&compile(body), out.path()).map_err(|e| e.to_string())?;
    Ok(std::fs::read_to_string(out.path().join("cli.rs")).unwrap())
}

/// A method `Do` with these options, whose request and answer have these fields.
fn method(options: &str, request: &str, answer: &str) -> String {
    format!(
        "service S {{ rpc Do(Req) returns (Ans) {{ {options} }} }}\n\
         message Req {{ {request} }}\nmessage Ans {{ {answer} }}"
    )
}

const CLI: &str = r#"option (ironflowx.v1.cli) = "do";"#;
const SUMMARY: &str = r#"option (ironflowx.v1.summary) = "Do it";"#;
const EXAMPLE: &str = r#"option (ironflowx.v1.example) = "{}";"#;

fn example(json: &str) -> String {
    format!("{CLI} {SUMMARY} option (ironflowx.v1.example) = {json:?};")
}

